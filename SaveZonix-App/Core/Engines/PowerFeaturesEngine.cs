using System.Diagnostics;
using System.Text.Json;
using System.Text.Json.Serialization;
using YoutubeExplode;
using YoutubeExplode.Videos.ClosedCaptions;

namespace Zonix.Core.Engines;

public record SponsorSegment(
    [property: JsonPropertyName("category")] string Category,
    [property: JsonPropertyName("segment")] double[] Segment
);

public record SubtitleTrackInfo(
    string LanguageName,
    string LanguageCode,
    bool IsAutoGenerated,
    string Format
);

/// <summary>
/// Powerhouse Feature Engine for SaveZonix:
/// - SponsorBlock automatic segment removal
/// - Subtitle extraction & MKV/MP4 container embedding
/// - Video time trimming / clipping before download
/// - Studio-grade 320kbps MP3 extraction with embedded ID3v2 album art
/// </summary>
public class PowerFeaturesEngine
{
    private readonly HttpClient _httpClient;
    private readonly TranscoderEngine _transcoder;
    private readonly YoutubeClient _youtubeClient;

    public PowerFeaturesEngine(TranscoderEngine transcoder, HttpClient? httpClient = null)
    {
        _transcoder = transcoder;
        _httpClient = httpClient ?? new HttpClient { Timeout = TimeSpan.FromSeconds(15) };
        _youtubeClient = YouTubeClientFactory.SharedClient;
    }

    /// <summary>
    /// Queries the SponsorBlock public API to find sponsor, intro, and selfpromo segments for a YouTube video.
    /// </summary>
    public async Task<List<SponsorSegment>> GetSponsorSegmentsAsync(string videoId, CancellationToken ct = default)
    {
        if (string.IsNullOrWhiteSpace(videoId)) return [];

        try
        {
            string url = $"https://sponsor.ajay.app/api/skipSegments?videoID={Uri.EscapeDataString(videoId)}&categories=[\"sponsor\",\"intro\",\"outro\",\"selfpromo\",\"preview\"]";
            using var req = new HttpRequestMessage(HttpMethod.Get, url);
            using var resp = await _httpClient.SendAsync(req, ct);

            if (!resp.IsSuccessStatusCode) return [];

            var json = await resp.Content.ReadAsStringAsync(ct);
            var segments = JsonSerializer.Deserialize<List<SponsorSegment>>(json);
            return segments ?? [];
        }
        catch (Exception ex)
        {
            CrashGuard.LogMessage($"SponsorBlock API query skipped: {ex.Message}");
            return [];
        }
    }

    /// <summary>
    /// Fetches all available subtitle tracks for a YouTube video.
    /// </summary>
    public async Task<List<SubtitleTrackInfo>> GetAvailableSubtitlesAsync(string videoId, CancellationToken ct = default)
    {
        if (string.IsNullOrWhiteSpace(videoId)) return [];

        try
        {
            var trackManifest = await _youtubeClient.Videos.ClosedCaptions.GetManifestAsync(videoId, ct);
            return trackManifest.Tracks.Select(t => new SubtitleTrackInfo(
                LanguageName: t.Language.Name,
                LanguageCode: t.Language.Code,
                IsAutoGenerated: t.IsAutoGenerated,
                Format: "SRT"
            )).ToList();
        }
        catch (Exception ex)
        {
            CrashGuard.LogMessage($"Subtitles probe skipped for {videoId}: {ex.Message}");
            return [];
        }
    }

    /// <summary>
    /// Downloads a closed caption track and saves it as an SRT file.
    /// </summary>
    public async Task<string?> DownloadSubtitleSrtAsync(string videoId, string languageCode, string outputSrtPath, CancellationToken ct = default)
    {
        try
        {
            var trackManifest = await _youtubeClient.Videos.ClosedCaptions.GetManifestAsync(videoId, ct);
            var track = trackManifest.Tracks.FirstOrDefault(t => t.Language.Code.Equals(languageCode, StringComparison.OrdinalIgnoreCase))
                        ?? trackManifest.Tracks.FirstOrDefault(t => t.Language.Code.StartsWith(languageCode, StringComparison.OrdinalIgnoreCase))
                        ?? trackManifest.Tracks.FirstOrDefault();

            if (track == null) return null;

            string? dir = Path.GetDirectoryName(outputSrtPath);
            if (!string.IsNullOrEmpty(dir) && !Directory.Exists(dir)) Directory.CreateDirectory(dir);

            await _youtubeClient.Videos.ClosedCaptions.DownloadAsync(track, outputSrtPath, cancellationToken: ct);
            return File.Exists(outputSrtPath) ? outputSrtPath : null;
        }
        catch (Exception ex)
        {
            CrashGuard.LogCrashEvent($"DownloadSubtitleSrtAsync({videoId}, {languageCode})", ex);
            return null;
        }
    }

    /// <summary>
    /// Embeds an SRT subtitle track directly into an MP4/MKV video container without re-encoding video.
    /// </summary>
    public async Task<bool> EmbedSubtitlesAsync(string inputVideoPath, string inputSrtPath, string outputVideoPath, string langCode = "eng", CancellationToken ct = default)
    {
        if (!File.Exists(inputVideoPath) || !File.Exists(inputSrtPath)) return false;

        string ext = Path.GetExtension(outputVideoPath).ToLowerInvariant();
        string subCodec = ext == ".mkv" ? "srt" : "mov_text";

        string args = $"-i \"{inputVideoPath}\" -i \"{inputSrtPath}\" -c copy -c:s {subCodec} -metadata:s:s:0 language={langCode} \"{outputVideoPath}\" -y";
        return await RunFfmpegRawAsync(args, ct);
    }

    /// <summary>
    /// Trims / cuts a video between start and end timestamps.
    /// Uses ultra-fast stream seek (-ss and -to with -c copy).
    /// </summary>
    public async Task<bool> TrimVideoAsync(string inputPath, string outputPath, TimeSpan startTime, TimeSpan endTime, CancellationToken ct = default)
    {
        if (!File.Exists(inputPath)) return false;

        string startStr = startTime.ToString(@"hh\:mm\:ss\.fff");
        string durationStr = (endTime - startTime).ToString(@"hh\:mm\:ss\.fff");

        // Pass 1: Fast copy cut
        string fastArgs = $"-ss {startStr} -i \"{inputPath}\" -t {durationStr} -c copy -movflags +faststart \"{outputPath}\" -y";
        bool success = await RunFfmpegRawAsync(fastArgs, ct);

        if (success && File.Exists(outputPath) && new FileInfo(outputPath).Length > 1024)
        {
            return true;
        }

        // Pass 2: Fallback re-encode cut for non-keyframe alignment precision
        string preciseArgs = $"-ss {startStr} -i \"{inputPath}\" -t {durationStr} -c:v libx264 -preset veryfast -crf 20 -c:a aac -movflags +faststart \"{outputPath}\" -y";
        return await RunFfmpegRawAsync(preciseArgs, ct);
    }

    /// <summary>
    /// Extracts Studio-Quality MP3 (320 kbps) with embedded cover art thumbnail, Artist, Title, and Album metadata.
    /// </summary>
    public async Task<bool> ExtractStudioAudioWithArtworkAsync(
        string inputMediaOrAudioPath,
        string outputMp3Path,
        string? thumbnailPath,
        string title,
        string artist,
        CancellationToken ct = default)
    {
        if (!File.Exists(inputMediaOrAudioPath)) return false;

        string safeTitle = title.Replace("\"", "'");
        string safeArtist = artist.Replace("\"", "'");

        string args;
        if (!string.IsNullOrEmpty(thumbnailPath) && File.Exists(thumbnailPath))
        {
            // Embed thumbnail as ID3v2 APIC cover art
            args = $"-i \"{inputMediaOrAudioPath}\" -i \"{thumbnailPath}\" -map 0:a -map 1:0 -c:a libmp3lame -b:a 320k -c:v copy -id3v2_version 3 " +
                   $"-metadata:s:v title=\"Album cover\" -metadata:s:v comment=\"Cover (front)\" " +
                   $"-metadata title=\"{safeTitle}\" -metadata artist=\"{safeArtist}\" -metadata album=\"{safeArtist}\" \"{outputMp3Path}\" -y";
        }
        else
        {
            args = $"-i \"{inputMediaOrAudioPath}\" -vn -c:a libmp3lame -b:a 320k -id3v2_version 3 " +
                   $"-metadata title=\"{safeTitle}\" -metadata artist=\"{safeArtist}\" \"{outputMp3Path}\" -y";
        }

        return await RunFfmpegRawAsync(args, ct);
    }

    private async Task<bool> RunFfmpegRawAsync(string args, CancellationToken ct)
    {
        try
        {
            var psi = new ProcessStartInfo
            {
                FileName = _transcoder.FfmpegPath,
                Arguments = args,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                CreateNoWindow = true
            };

            using var proc = Process.Start(psi);
            if (proc == null) return false;

            await proc.WaitForExitAsync(ct);
            return proc.ExitCode == 0;
        }
        catch (Exception ex)
        {
            CrashGuard.LogCrashEvent($"RunFfmpegRawAsync: {args}", ex);
            return false;
        }
    }
}
